// Runs after `expo export -p web`. Writes dist/sw.js with a precache list of the built files,
// so the installed app opens and works fully offline.
import { createHash } from 'node:crypto';
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';

// GitHub Pages: skip Jekyll (it hides the _expo folder) and serve the app for unknown paths.
writeFileSync(join(DIST, '.nojekyll'), '');
copyFileSync(join(DIST, 'index.html'), join(DIST, '404.html'));
const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push('./' + relative(DIST, p).split(sep).join('/'));
  }
})(DIST);

// Skip the icon fonts the app never uses (only Ionicons is used) and build metadata.
const precache = files.filter(
  (f) => f !== './metadata.json' && f !== './index.html' && f !== './404.html' && f !== './.nojekyll' && !(f.endsWith('.ttf') && !f.includes('/Ionicons.')),
);
precache.unshift('./');

const hash = createHash('sha256');
for (const f of precache) hash.update(f === './' ? readFileSync(join(DIST, 'index.html')) : f);
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = 'daymark-${version}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('daymark-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;

  // Pages: try the network first so updates arrive, fall back to the cached app shell offline.
  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./')),
    );
    return;
  }

  // Everything else (hashed JS, fonts, icons): cache first.
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js written: cache daymark-${version}, ${precache.length} files precached`);
