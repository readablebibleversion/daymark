import React, { useState } from 'react';
import { createRoot } from 'react-dom/client';
import { App } from './App';
import { isUnlocked, lock } from './lock';
import { LockScreen } from './LockScreen';
import { StoreProvider } from './store';
import '@fontsource-variable/fredoka/wght.css';
import './styles.css';

/** Shows the lock screen until the password is entered; the app (and its data) only loads after. */
function Gate() {
  const [open, setOpen] = useState(isUnlocked);
  if (!open) return <LockScreen onUnlock={() => setOpen(true)} />;
  return (
    <StoreProvider>
      <App onLock={() => { lock(); setOpen(false); window.scrollTo({ top: 0 }); }} />
    </StoreProvider>
  );
}

createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <Gate />
  </React.StrictMode>,
);

// Offline support: sw.js is generated by `npm run build` (not present in dev).
if ('serviceWorker' in navigator && import.meta.env.PROD) {
  window.addEventListener('load', () => {
    navigator.storage?.persist?.();
    navigator.serviceWorker.register(`${import.meta.env.BASE_URL}sw.js`).catch((e) => console.warn('SW registration failed', e));
  });
}
